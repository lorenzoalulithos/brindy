export const gameById = (id: string) => GAMES.find((g) => g.id === id)

/** Days until release (0 = available). Everything is unlocked in dev builds and in review builds (VITE_REVIEW_BUILD=1). */
export function daysUntilRelease(g: GameDef, now = Date.now()): number {
  if (!g.releaseAt || import.meta.env.DEV || REVIEW_BUILD) return 0
  const diff = new Date(g.releaseAt + 'T00:00:00').getTime() - now
  return diff > 0 ? Math.ceil(diff / 86_400_000) : 0
}
